const BY_SLUG = new Map(CATEGORIES.map((category) => [category.slug, category]));

export function categoryBySlug(slug) {
  return BY_SLUG.get(String(slug || "").toLowerCase()) || null;
}

export function priceSentence(priceLabel) {
  if (!priceLabel) {
    return "A guide price is available on request. Cemetery permit fees are extra and vary by cemetery.";
  }
  return `Guide prices start from ${priceLabel}. The price covers the stone, the lettering on the design, and installation. Cemetery permit fees are extra and vary by cemetery.`;
}

export function closingSentence() {
  return "Installation is across Greater London and surrounds. The showroom at 1 The Market Place, Falloden Way, London NW11 6LB is open Monday to Friday, 10am to 3pm. Ask for a quote when you are ready. We reply within one working day.";
}

export function introText(category, priceLabel) {
  return [...category.paragraphs, priceSentence(priceLabel), closingSentence()].join(" ");
}

export function wordCount(text) {
  return String(text || "").trim().split(/\s+/).filter(Boolean).length;
}
